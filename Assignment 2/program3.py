## Area of rectangle

len1=float(input('Enter the length of rectangle: '))
width1=float(input('Enter the width of the rectangle: '))
area1=(len1*width1)
print(f'Area of rectangle is {area1}')


## Area of triangle

base=float(input('Enter the base of triangle: '))
height=float(input('Enter the height of triangle: '))
area=(base*height)/2
print(f'Area of given triangle is {area}')
